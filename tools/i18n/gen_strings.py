#!/usr/bin/env python3
"""Generates app/src/main/res/values/strings.xml from the Persian string tables."""
import importlib.util, pathlib, re, sys
HERE = pathlib.Path(__file__).parent
ROOT = HERE.parents[1]
S = {}
for part in sorted(HERE.glob("strings_fa_part*.py")):
    spec = importlib.util.spec_from_file_location(part.stem, part)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    dup = set(S) & set(m.S)
    if dup:
        sys.exit(f"duplicate keys: {dup}")
    S.update(m.S)

def esc(v: str) -> str:
    v = v.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    v = v.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if v.startswith("@") or v.startswith("?"):
        v = "\\" + v
    return v

out = ['<?xml version="1.0" encoding="utf-8"?>',
       '<!-- Generated by tools/i18n/gen_strings.py — edit the Python tables, not this file. -->',
       '<resources>']
for k in sorted(S):
    v = S[k]
    fmt = bool(re.search(r"%\d+\$", v))
    attrs = '' if fmt or '%' not in v else ' formatted="false"'
    out.append(f'    <string name="{k}"{attrs}>{esc(v)}</string>')
out.append('</resources>')
target = ROOT / "app/src/main/res/values/strings.xml"
target.write_text("\n".join(out) + "\n", encoding="utf-8")

# check that every referenced key exists
used = set()
for p in (ROOT / "app/src/main").rglob("*"):
    if p.suffix in (".kt", ".xml") and p.name != "strings.xml":
        t = p.read_text(encoding="utf-8", errors="ignore")
        used |= set(re.findall(r"R\.string\.([a-z0-9_]+)", t)) | set(re.findall(r"@string/([a-z0-9_]+)", t))
missing = sorted(used - set(S))
unused = sorted(set(S) - used)
print(f"{len(S)} strings written; {len(missing)} missing; {len(unused)} unused")
if missing:
    print("MISSING:", " ".join(missing))
if unused:
    print("UNUSED:", " ".join(unused))
sys.exit(1 if missing else 0)
